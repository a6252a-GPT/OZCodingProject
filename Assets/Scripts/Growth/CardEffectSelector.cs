public class CardEffectSelector : MonoBehaviour
{
    [Header("Setup")]
    [SerializeField] private CardEffect      cardEffect;
    [SerializeField] private Canvas          targetCanvas;
    [Tooltip("????????? TextMeshProUGUI ?????? (EffectFont)")]
    [SerializeField] private TextMeshProUGUI fontSource;   // ?????????font ?????

    [Header("??? ???????")]
    [SerializeField] private float panelWidth   = 320f;   // ???? ??? ???
    [SerializeField] private float panelHeight  = 320f;   // ??????? ???
    [SerializeField] private float tabHeight    = 28f;    // ?????? ??????? ???
    [SerializeField] private Vector2 panelOffset = new Vector2(8f, 8f); // ???????

    [Header("???/ ?? ???")]
    [Tooltip("?? ??? (px)")]
    [SerializeField] private float buttonHeightPx  = 22f;
    [Tooltip("?? ??????")]
    [SerializeField] private float buttonFontSize  = 10f;
    [Tooltip("??? ??????")]
    [SerializeField] private float headerFontSize  = 10f;
    [Tooltip("????????")]
    [SerializeField] private float tabFontSize     = 12f;

    [Header("Animation")]
    [SerializeField] private float slideTime = 0.22f;
    [SerializeField] private float autoCloseDelay = 0.4f; // ??????? ????? ????

    // ???? ??? ????????????????????????????????????????????????????????????????????????
    private static readonly Color PanelBg    = new Color(0.06f, 0.04f, 0.10f, 0.95f); // ??? ??: ???
    private static readonly Color TabBg      = new Color(0.28f, 0.08f, 0.45f, 1f);   // ??? ?:  ??
    private static readonly Color BtnNormal  = new Color(0.15f, 0.15f, 0.20f, 1f);
    private static readonly Color BtnRareSel = new Color(0.08f, 0.46f, 0.12f, 1f);
    private static readonly Color BtnUniqSel = new Color(0.50f, 0.40f, 0.00f, 1f);
    private static readonly Color HeaderRare  = new Color(0.30f, 1.00f, 0.35f, 1f);
    private static readonly Color HeaderUniq  = new Color(1.00f, 0.88f, 0.15f, 1f);
    private static readonly Color TextColor   = new Color(0.90f, 0.90f, 0.92f, 1f);

    // ???? ???? ??? ????????????????????????????????????????????????????????????????
    private RectTransform panelRT;
    private TextMeshProUGUI tabLabel;
    private bool isExpanded = false;
    private Tweener slideTween;
    private float leaveTimer = 0f;

    private readonly Dictionary<CardEffect.RareEffectKind,   Image> rareBtnImg   = new();
    private readonly Dictionary<CardEffect.UniqueEffectKind, Image> uniqueBtnImg = new();

    // ??????????????????????????????????????????????????????????????????????????????????????????
    //  ????
    // ??????????????????????????????????????????????????????????????????????????????????????????

    private void Start()
    {
        if (cardEffect == null)
            cardEffect = FindFirstObjectByType<CardEffect>();

        if (targetCanvas == null)
        {
            foreach (Canvas c in FindObjectsByType<Canvas>(FindObjectsSortMode.None))
            {
                if (c.name == "Canvas") { targetCanvas = c; break; }
            }
            if (targetCanvas == null)
                targetCanvas = FindFirstObjectByType<Canvas>();
        }

        if (cardEffect == null || targetCanvas == null)
        {
            Debug.LogWarning("[CardEffectSelector] CardEffect ??? Canvas ????? ???????");
            return;
        }

        BuildUI();
    }

    // ??Input System / ??Input System ??? ????
    private static Vector2 GetMousePosition()
    {
#if ENABLE_INPUT_SYSTEM
        var mouse = Mouse.current;
        return mouse != null ? mouse.position.ReadValue() : Vector2.zero;
#else
        return Input.mousePosition;
#endif
    }

    private void Update()
    {
        if (panelRT == null || !isExpanded) return;

        // ?????? ??? ????????????? ???
        Vector3[] corners = new Vector3[4];
        panelRT.GetWorldCorners(corners);
        Vector2 mp = GetMousePosition();

        bool inside = mp.x >= corners[0].x && mp.x <= corners[2].x &&
                      mp.y >= corners[0].y && mp.y <= corners[2].y;

        if (!inside)
        {
            leaveTimer += Time.unscaledDeltaTime;
            if (leaveTimer >= autoCloseDelay)
                Collapse();
        }
        else
        {
            leaveTimer = 0f;
        }
    }

    // ??????????????????????????????????????????????????????????????????????????????????????????
    //  UI ??
    // ??????????????????????????????????????????????????????????????????????????????????????????

    private void BuildUI()
    {
        float totalHeight = tabHeight + panelHeight;

        // ???? ?? ??? ??????????????????????????????????????????????????????????
        GameObject panelGO = new GameObject("EffectSelectorPanel");
        panelRT = panelGO.AddComponent<RectTransform>();
        panelGO.transform.SetParent(targetCanvas.transform, false);
        panelGO.transform.SetAsLastSibling();

        // ???????, pivot ???
        panelRT.anchorMin        = new Vector2(0f, 0f);
        panelRT.anchorMax        = new Vector2(0f, 0f);
        panelRT.pivot            = new Vector2(0f, 0f);
        panelRT.anchoredPosition = panelOffset;
        panelRT.sizeDelta        = new Vector2(panelWidth, tabHeight); // ???: ???? ??

        Image panelImg = panelGO.AddComponent<Image>();
        panelImg.color = PanelBg;

        // ???????? ??????????
        Mask panelMask = panelGO.AddComponent<Mask>();
        panelMask.showMaskGraphic = true;

        // ???? ??(??? ??, ??? ??????) ??????????????????
        BuildTab(panelRT, totalHeight);

        // ???? ???? ??????? ????????????????????????????????????
        BuildTwoColumnContent(panelRT, totalHeight);

        // ???? ?????? ?? ?? ????????????????????????????????????????
        Canvas.ForceUpdateCanvases();
        LayoutRebuilder.ForceRebuildLayoutImmediate(panelRT);

        RefreshHighlights();
    }

    private void BuildTab(RectTransform parent, float totalHeight)
    {
        GameObject tabGO = new GameObject("Tab");
        tabGO.transform.SetParent(parent, false);
        RectTransform tabRT = tabGO.AddComponent<RectTransform>();

        // ??? ??? (Y=0 ???) ????
        tabRT.anchorMin        = new Vector2(0f, 0f);
        tabRT.anchorMax        = new Vector2(1f, 0f);
        tabRT.pivot            = new Vector2(0.5f, 0f);
        tabRT.anchoredPosition = Vector2.zero;
        tabRT.sizeDelta        = new Vector2(0f, tabHeight);

        Image tabImg = tabGO.AddComponent<Image>();
        tabImg.color = TabBg;

        Button tabBtn = tabGO.AddComponent<Button>();
        tabBtn.targetGraphic = tabImg;
        ColorBlock cb = tabBtn.colors;
        cb.normalColor      = Color.white;
        cb.highlightedColor = new Color(1.2f, 1.2f, 1.2f, 1f);
        cb.pressedColor     = new Color(0.8f, 0.8f, 0.8f, 1f);
        tabBtn.colors = cb;
        tabBtn.onClick.AddListener(TogglePanel);

        GameObject textGO = new GameObject("Label");
        textGO.transform.SetParent(tabGO.transform, false);
        RectTransform textRT = textGO.AddComponent<RectTransform>();
        textRT.anchorMin = Vector2.zero;
        textRT.anchorMax = Vector2.one;
        textRT.offsetMin = textRT.offsetMax = Vector2.zero;

        tabLabel = textGO.AddComponent<TextMeshProUGUI>();
        tabLabel.enableWordWrapping = false;
        tabLabel.overflowMode       = TextOverflowModes.Overflow;
        tabLabel.fontSize           = tabFontSize;
        tabLabel.color              = new Color(0.95f, 0.80f, 1.00f, 1f); // ??? ??
        tabLabel.fontStyle          = FontStyles.Bold;
        tabLabel.alignment          = TextAlignmentOptions.Center;
        if (fontSource != null) tabLabel.font = fontSource.font;
        tabLabel.text = "[ 이팩트 ]";
    }

    private void BuildTwoColumnContent(RectTransform parent, float totalHeight)
    {
        // ???????????
        GameObject contentArea = new GameObject("ContentArea");
        contentArea.transform.SetParent(parent, false);
        RectTransform contentRT = contentArea.AddComponent<RectTransform>();

        contentRT.anchorMin        = new Vector2(0f, 0f);
        contentRT.anchorMax        = new Vector2(1f, 1f);
        contentRT.offsetMin        = new Vector2(0f, tabHeight);   // ????
        contentRT.offsetMax        = Vector2.zero;

        HorizontalLayoutGroup hlg = contentArea.AddComponent<HorizontalLayoutGroup>();
        hlg.spacing            = 2f;
        hlg.padding            = new RectOffset(3, 3, 3, 3);
        hlg.childAlignment     = TextAnchor.UpperLeft;
        hlg.childControlWidth  = true;
        hlg.childControlHeight = true;
        hlg.childForceExpandWidth  = true;
        hlg.childForceExpandHeight = true;

        // ???? ???: ??? ??????????????????????????????????????????????????????
        RectTransform rareContent = BuildColumn(contentArea.transform, "레어", HeaderRare);
        foreach (CardEffect.RareEffectKind kind in Enum.GetValues(typeof(CardEffect.RareEffectKind)))
        {
            if (kind == CardEffect.RareEffectKind.None) continue;
            CardEffect.RareEffectKind k = kind;
            Button btn = AddButton(rareContent, FormatLabel(kind.ToString()), () => OnSelectRare(k));
            rareBtnImg[kind] = btn.GetComponent<Image>();
        }
        LayoutRebuilder.ForceRebuildLayoutImmediate(rareContent);

        // ???? ????? ???????????????????????????????????????????????????
        RectTransform uniqContent = BuildColumn(contentArea.transform, "유니크", HeaderUniq);
        foreach (CardEffect.UniqueEffectKind kind in Enum.GetValues(typeof(CardEffect.UniqueEffectKind)))
        {
            if (kind == CardEffect.UniqueEffectKind.None) continue;
            CardEffect.UniqueEffectKind k = kind;
            Button btn = AddButton(uniqContent, FormatLabel(kind.ToString()), () => OnSelectUnique(k));
            uniqueBtnImg[kind] = btn.GetComponent<Image>();
        }
        LayoutRebuilder.ForceRebuildLayoutImmediate(uniqContent);
    }

    // ????????? ??? ?????????? Content RectTransform ??
    private RectTransform BuildColumn(Transform parent, string headerText, Color headerColor)
    {
        GameObject colGO = new GameObject($"Column_{headerText}");
        colGO.transform.SetParent(parent, false);
        colGO.AddComponent<RectTransform>(); // HLG ? ??? ???
        Image colImg = colGO.AddComponent<Image>();
        colImg.color = new Color(0f, 0f, 0f, 0.3f);

        // ScrollRect
        ScrollRect scroll = colGO.AddComponent<ScrollRect>();

        // Viewport
        GameObject vpGO = new GameObject("Viewport");
        vpGO.transform.SetParent(colGO.transform, false);
        RectTransform vpRT = vpGO.AddComponent<RectTransform>();
        vpRT.anchorMin = Vector2.zero;
        vpRT.anchorMax = Vector2.one;
        vpRT.offsetMin = Vector2.zero;
        vpRT.offsetMax = Vector2.zero;
        Image vpImg = vpGO.AddComponent<Image>();
        vpImg.color = new Color(1f, 1f, 1f, 0.01f);
        Mask mask = vpGO.AddComponent<Mask>();
        mask.showMaskGraphic = false;

        // Content
        GameObject contentGO = new GameObject("Content");
        contentGO.transform.SetParent(vpGO.transform, false);
        RectTransform contentRT = contentGO.AddComponent<RectTransform>();
        contentRT.anchorMin        = new Vector2(0f, 1f);
        contentRT.anchorMax        = new Vector2(1f, 1f);
        contentRT.pivot            = new Vector2(0.5f, 1f);
        contentRT.anchoredPosition = Vector2.zero;
        contentRT.sizeDelta        = Vector2.zero;

        VerticalLayoutGroup vlg = contentGO.AddComponent<VerticalLayoutGroup>();
        vlg.spacing            = 2f;
        vlg.padding            = new RectOffset(3, 3, 3, 3);
        vlg.childAlignment     = TextAnchor.UpperCenter;
        vlg.childControlWidth  = true;
        vlg.childControlHeight = false;
        vlg.childForceExpandWidth  = true;
        vlg.childForceExpandHeight = false;

        ContentSizeFitter csf = contentGO.AddComponent<ContentSizeFitter>();
        csf.verticalFit = ContentSizeFitter.FitMode.PreferredSize;

        scroll.viewport          = vpRT;
        scroll.content           = contentRT;
        scroll.horizontal        = false;
        scroll.vertical          = true;
        scroll.scrollSensitivity = 35f;
        scroll.movementType      = ScrollRect.MovementType.Clamped;

        // ??? ???
        AddHeader(contentRT, headerText, headerColor);

        return contentRT;
    }

    private void AddHeader(Transform parent, string text, Color color)
    {
        GameObject go = new GameObject("Header");
        go.transform.SetParent(parent, false);
        // ??? ??????????????? ??? ??
        go.AddComponent<RectTransform>().sizeDelta = new Vector2(0f, headerFontSize + 10f);
        TextMeshProUGUI tmp = go.AddComponent<TextMeshProUGUI>();
        tmp.enableWordWrapping = false;
        tmp.overflowMode       = TextOverflowModes.Overflow;
        tmp.color              = color;
        tmp.fontSize           = headerFontSize;
        tmp.fontStyle          = FontStyles.Bold;
        tmp.alignment          = TextAlignmentOptions.Center;
        if (fontSource != null) tmp.font = fontSource.font;
        tmp.text = text;
    }

    private Button AddButton(Transform parent, string label, Action onClick)
    {
        GameObject go = new GameObject($"Btn_{label}");
        go.transform.SetParent(parent, false);
        go.AddComponent<RectTransform>().sizeDelta = new Vector2(0f, buttonHeightPx);

        Image img = go.AddComponent<Image>();
        img.color = BtnNormal;

        Button btn = go.AddComponent<Button>();
        ColorBlock cb     = btn.colors;
        cb.normalColor    = Color.white;
        cb.highlightedColor = new Color(1.15f, 1.15f, 1.15f, 1f);
        cb.pressedColor   = new Color(0.7f, 0.7f, 0.7f, 1f);
        btn.colors        = cb;
        btn.targetGraphic = img;
        btn.onClick.AddListener(() => onClick());

        GameObject textGO = new GameObject("Text");
        textGO.transform.SetParent(go.transform, false);
        RectTransform tRT = textGO.AddComponent<RectTransform>();
        tRT.anchorMin = Vector2.zero;
        tRT.anchorMax = Vector2.one;
        tRT.offsetMin = new Vector2(5f, 0f);
        tRT.offsetMax = new Vector2(-3f, 0f);

        TextMeshProUGUI tmp = textGO.AddComponent<TextMeshProUGUI>();
        tmp.enableWordWrapping = false;
        tmp.overflowMode       = TextOverflowModes.Overflow;
        tmp.fontSize           = buttonFontSize;
        tmp.color              = TextColor;
        tmp.alignment          = TextAlignmentOptions.MidlineLeft;
        if (fontSource != null) tmp.font = fontSource.font;
        tmp.text = label;

        return btn;
    }

