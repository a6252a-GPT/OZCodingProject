    private static string FormatLabel(string enumName)
    {
        string s = enumName
            .Replace("_Loop_G", " Loop").Replace("_Loop_Y", " Loop")
            .Replace("_G", "").Replace("_Y", "");

        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < s.Length; i++)
        {
            if (i > 0 && char.IsUpper(s[i]) && !char.IsUpper(s[i - 1]))
                sb.Append(' ');
            sb.Append(s[i]);
        }
        return sb.ToString().Trim();
    }
