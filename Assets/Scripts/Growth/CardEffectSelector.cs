    private void TogglePanel()
    {
        if (isExpanded) Collapse();
        else Expand();
    }

    private void Expand()
    {
        if (isExpanded) return;
        isExpanded = true;
        leaveTimer = 0f;

        slideTween?.Kill();
        slideTween = panelRT
            .DOSizeDelta(new Vector2(panelWidth, tabHeight + panelHeight), slideTime)
            .SetUpdate(true)
            .SetEase(Ease.OutCubic);

        if (tabLabel != null) tabLabel.text = "^ 이팩트 ^";
    }

    private void Collapse()
    {
        if (!isExpanded) return;
        isExpanded = false;
        leaveTimer = 0f;

        slideTween?.Kill();
        slideTween = panelRT
            .DOSizeDelta(new Vector2(panelWidth, tabHeight), slideTime)
            .SetUpdate(true)
            .SetEase(Ease.InCubic);

        if (tabLabel != null) tabLabel.text = "[ 이팩트 ]";
    }

    // ??????????????????????????????????????????????????????????????????????????????????????????
    //  ?? ??? ??
    // ??????????????????????????????????????????????????????????????????????????????????????????

    private void OnSelectRare(CardEffect.RareEffectKind kind)
    {
        cardEffect.SetRareEffect(kind);
        RefreshHighlights();
    }

    private void OnSelectUnique(CardEffect.UniqueEffectKind kind)
    {
        cardEffect.SetUniqueEffect(kind);
        RefreshHighlights();
    }

    private void RefreshHighlights()
    {
        foreach (var kv in rareBtnImg)
            kv.Value.color = kv.Key == cardEffect.CurrentRare ? BtnRareSel : BtnNormal;
        foreach (var kv in uniqueBtnImg)
            kv.Value.color = kv.Key == cardEffect.CurrentUnique ? BtnUniqSel : BtnNormal;
    }

